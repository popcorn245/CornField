// Type declarations for the tags: StencilRS's Vite build writes none (https://github.com/popcorn245/StencilRS/issues/54), so they are written here from
// StencilRS's own analyze() output, which carries each component's tag, properties (with types), events and methods. Until a StencilRS release
// emits them, this is how `HTMLCornMapElement`, `HTMLElementTagNameMap['corn-map']` and a typed `CustomEvent` detail reach a consumer's editor.
//
//   writeTypes(outDir)   dist/types/components.d.ts, index.d.ts and one <name>.d.ts per component
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { analyze } from '@popcorn245/stencilrs';
import { PACKAGE } from './shared.mjs';

const pascal = (tag) => tag.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const doc = (text, indent = '    ') => (text ? `${indent}/** ${text.replace(/\*\//g, '* /').replace(/\s+/g, ' ').trim()} */\n` : '');

/** The analyzed components of src/components/<name>/<name>.tsx, in tag order */
export function analyzeComponents() {
  const dir = join(PACKAGE, 'src', 'components');
  const out = [];
  for (const name of readdirSync(dir)) {
    const file = join(dir, name, `${name}.tsx`);
    const result = analyze(readFileSync(file, 'utf8'), file, { complexTypes: false, resolveImports: true });
    const errors = (result.diagnostics || []).filter((d) => d.level === 'error' || d.severity === 'error');
    if (errors.length) throw new Error(`${name}.tsx: ${errors.map((d) => d.messageText || d.message).join('; ')}`);
    const source = readFileSync(file, 'utf8');
    out.push(...result.components.map((c) => ({ ...c, localTypes: localTypes(c, source) })));
  }
  return out.sort((a, b) => (a.tagName < b.tagName ? -1 : 1));
}

/** The text of `export interface Name {…}` or `export type Name = …;` in a component's source */
function declarationOf(source, name) {
  const at = source.search(new RegExp(`^export (?:interface|type) ${name}\\b`, 'm'));
  if (at < 0) throw new Error(`the type ${name} is used by a property, event or method but not exported from the component's source`);
  const open = source.indexOf('{', at);
  const semi = source.indexOf(';', at);
  if (/^export type/.test(source.slice(at)) && (open < 0 || semi < open)) return source.slice(at, semi + 1);
  let depth = 0;
  for (let i = open; i < source.length; i++) {
    if (source[i] === '{') depth++;
    else if (source[i] === '}' && --depth === 0) return source.slice(at, i + 1 + (source[i + 1] === ';' ? 1 : 0));
  }
  throw new Error(`the type ${name} is never closed`);
}

/** The types a component declares in its own file and names in a property, event or method: a consumer needs their declarations too */
function localTypes(c, source) {
  const names = new Set();
  for (const m of [...c.properties, ...c.events, ...c.methods]) {
    const refs = (m.complexType && m.complexType.references) || {};
    for (const [name, ref] of Object.entries(refs)) if (ref && ref.location === 'local') names.add(name);
  }
  return [...names].sort().map((name) => declarationOf(source, name));
}

/** A property's type as written in the source (the `original` text: resolved types print object literals as ''), with `undefined` when it is optional */
function typeOf(p) {
  const t = (p.complexType && p.complexType.original) || p.complexTypeOriginal || p.type || 'unknown';
  return p.optional && !/\bundefined\b/.test(t) ? `${t} | undefined` : t;
}

export function typesFor(components) {
  const cls = (c) => c.componentClassName;
  const parts = ['// Generated by components/scripts/types.mjs from the components\' own declarations (StencilRS emits no types for a library build: StencilRS#54). Do not edit.', ''];
  for (const c of components) for (const text of c.localTypes || []) parts.push(text, '');
  parts.push('export namespace Components {');
  for (const c of components) {
    parts.push(`  interface ${cls(c)} {`);
    for (const p of c.properties) parts.push(`${doc(p.docs && p.docs.text)}    '${p.name}'${p.optional ? '?' : ''}: ${typeOf(p)};`);
    for (const m of c.methods) parts.push(`${doc(m.docs && m.docs.text)}    '${m.name}': ${m.complexType.signature};`);
    parts.push('  }');
  }
  parts.push('}', '');
  for (const c of components) {
    parts.push(`export interface ${cls(c)}CustomEvent<T> extends CustomEvent<T> {`, '  detail: T;', `  target: HTML${cls(c)}Element;`, '}', '');
  }
  // For a JSX consumer (React, Preact, Stencil): the tags as intrinsic elements, with the properties optional and an `on<Event>` per event.
  // Nothing global: a consumer merges `LocalJSX.IntrinsicElements` into its framework's own JSX namespace (docs/embedding.md shows how).
  parts.push('export namespace LocalJSX {');
  for (const c of components) {
    parts.push(`  interface ${cls(c)} {`);
    for (const p of c.properties) parts.push(`    '${p.name}'?: ${typeOf(p)};`);
    for (const e of c.events) parts.push(`    'on${e.name[0].toUpperCase()}${e.name.slice(1)}'?: (event: ${cls(c)}CustomEvent<${(e.complexType && e.complexType.original) || 'unknown'}>) => void;`);
    parts.push('  }');
  }
  parts.push('  interface IntrinsicElements {');
  for (const c of components) parts.push(`    '${c.tagName}': LocalJSX.${cls(c)} & { [attribute: string]: unknown };`);
  parts.push('  }', '}', '');
  parts.push('declare global {');
  for (const c of components) {
    const N = cls(c);
    parts.push(`  /** What \`<${c.tagName}>\` sends: the event's name and the type of its \`detail\` */`, `  interface HTML${N}ElementEventMap {`);
    for (const e of c.events) parts.push(`${doc(e.docs && e.docs.text, '    ')}    '${e.name}': ${(e.complexType && e.complexType.original) || 'unknown'};`);
    parts.push('  }');
    const listen = (verb, opts) => [
      `    ${verb}EventListener<K extends keyof HTML${N}ElementEventMap>(type: K, listener: (this: HTML${N}Element, ev: ${N}CustomEvent<HTML${N}ElementEventMap[K]>) => any, options?: ${opts}): void;`,
      `    ${verb}EventListener<K extends keyof HTMLElementEventMap>(type: K, listener: (this: HTML${N}Element, ev: HTMLElementEventMap[K]) => any, options?: ${opts}): void;`,
      `    ${verb}EventListener(type: string, listener: EventListenerOrEventListenerObject, options?: ${opts}): void;`,
    ];
    parts.push(`${doc(c.docs && c.docs.text, '  ')}  interface HTML${N}Element extends Components.${N}, HTMLElement {`, ...listen('add', 'boolean | AddEventListenerOptions'), ...listen('remove', 'boolean | EventListenerOptions'), '  }');
    parts.push(`  var HTML${N}Element: { prototype: HTML${N}Element; new (): HTML${N}Element };`, '');
  }
  parts.push('  interface HTMLElementTagNameMap {');
  for (const c of components) parts.push(`    '${c.tagName}': HTML${cls(c)}Element;`);
  parts.push('  }', '}', '');
  const index = [
    // `.js`: a consumer under moduleResolution node16/nodenext needs the extension (TypeScript maps it to components.d.ts); bundler takes it too
    "export * from './components.js';",
    '/** The version of cornfield these components were built from (the server reports the same number) */',
    'export declare const version: string;',
    ...components.map((c) => `export declare const ${cls(c)}: { prototype: HTML${cls(c)}Element; new (): HTML${cls(c)}Element };`),
    '',
  ].join('\n');
  const files = { 'components.d.ts': `${parts.join('\n')}\n`, 'index.d.ts': index };
  for (const c of components) files[`${c.tagName}.d.ts`] = `export * from './components.js';\nexport declare const ${cls(c)}: { prototype: HTML${cls(c)}Element; new (): HTML${cls(c)}Element };\n`;
  return files;
}

export function writeTypes(outDir) {
  const files = typesFor(analyzeComponents());
  mkdirSync(outDir, { recursive: true });
  for (const [name, text] of Object.entries(files)) writeFileSync(join(outDir, name), text);
  return Object.keys(files);
}
